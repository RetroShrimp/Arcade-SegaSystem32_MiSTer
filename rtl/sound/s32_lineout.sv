// s32_lineout.sv — the System 32 line-out analog chain as digital IIRs.
//
// References: schematic sheet 8/9 (171-5964D 837-7422 "SYSTEM32 FM/PCM
// SOUND"), traced 2026-11-04 — docs/sound-design.md "WP-G3
// implementation"; OPEN-QUESTIONS Q23. Coefficients and their check
// against the analog network (and ngspice): tools/s32_audio_filter.py.
//
// What the board does, per channel (L shown; R is the mirror):
//   FM   both YM3438 MOL -> 100K each -> IC9 inverting summer with
//        47K || 470pF feedback: gain -0.47 per chip, pole 7.2 kHz
//   PCM  LC7881 CH1 -> IC4 buffer -> 2.2uF into 2.2K (high-pass
//        32.9 Hz) -> 2.2K / 6800pF ladder + unity Sallen-Key
//        (2.2K, 2.2K, 0.018uF, 1000pF): third-order low-pass with a
//        real pole at 15.1 kHz and a pair at 14.3 kHz, Q 1.008
//   OUT  IC9 inverting line-out stage: FM via 20K, PCM via 47K,
//        feedback 20K || 220pF (pole 36.2 kHz)
// FM is inverted twice and PCM once, so PCM reaches the line out with
// the opposite sign to FM; this module keeps that (it assumes both
// DACs put positive codes out as positive volts).
//
// Levels: the schematic does not give the YM3438 or LC7881 volts per
// code, so the FM:PCM balance stays MAME's 0.30 / 0.40 (the 77/256 and
// 102/256 the raw mix used). Passband gains are therefore exactly the
// raw mix's; only the frequency shaping and the PCM sign are new.
// Left out: the coupling corners below 2 Hz (the MiSTer framework's DC
// blocker sits at ~7.5 Hz anyway).
//
// Implementation: bilinear-transform sections at fs = clk/256
// (251.7 kHz with s32_sys's 64.4318 MHz clk; `tick` must pulse once
// per 256 clk for the coefficients to hold). One multiplier steps
// through 11 multiply-accumulates per channel, 4 clk each (operand
// register, multiply, accumulate, store/advance): 88 of the
// 256 clk per sample. Samples are Q20.16 in 36 bits; coefficients
// Q3.22 in 25 bits. Quantised response vs the analog network: within
// 0.14 dB from 20 Hz to 20 kHz (the generator's report).
//
//   f  = FM_B (xf + xf1) - FM_A1 f1          FM pole (gain folded in)
//   h  = HP_B (xp - xp1) - HP_A1 h1          PCM high-pass
//   p  = P1_B (h + h1)   - P1_A1 p1          PCM real pole
//   q  = BQ_B (p + 2p1 + p2) - BQ_A1 q1 - BQ_A2 q2   PCM pair (gain,
//                                            sign folded in)
//   m  = f + q;  o = LO_B (m + m1) - LO_A1 o1      line-out pole

module s32_lineout (
    input  logic               clk,
    input  logic               rst,
    input  logic               tick,       // one per 256 clk
    input  logic signed [16:0] fm_l,       // YM1 + YM2, raw jt12 units
    input  logic signed [16:0] fm_r,
    input  logic signed [15:0] pcm_l,      // RF5C68 output
    input  logic signed [15:0] pcm_r,
    output logic signed [15:0] out_l,
    output logic signed [15:0] out_r
);

    // generated by tools/s32_audio_filter.py (Q3.22 signed, fs = clk/256)
    localparam logic signed [24:0] C_FM_B  =    104352;
    localparam logic signed [24:0] C_FM_A1 =  -3500430;
    localparam logic signed [24:0] C_HP_B  =   4192583;
    localparam logic signed [24:0] C_HP_A1 =  -4190862;
    localparam logic signed [24:0] C_P1_B  =    673150;
    localparam logic signed [24:0] C_P1_A1 =  -2848003;
    localparam logic signed [24:0] C_BQ_B  =    -44881;
    localparam logic signed [24:0] C_BQ_A1 =  -6699065;
    localparam logic signed [24:0] C_BQ_A2 =   2955328;
    localparam logic signed [24:0] C_LO_B  =   1369677;
    localparam logic signed [24:0] C_LO_A1 =  -1454950;

    localparam int CF = 22;          // coefficient fraction bits
    localparam int SF = 16;          // sample fraction bits
    localparam int NSTEP = 11;

    typedef logic signed [35:0] smp_t;

    // per-channel state (index 0 = L, 1 = R)
    smp_t xf1 [2], f1 [2], xp1 [2], h1 [2], p1 [2], p2 [2];
    smp_t q1 [2], q2 [2], m1 [2], o1 [2];
    // this sample's inputs and section results
    smp_t xf [2], xp [2];
    smp_t f_t, h_t, p_t, q_t;

    logic       busy, ch;
    logic [3:0] step;
    logic [1:0] ph;

    logic signed [37:0] opnd, op_q;
    logic signed [24:0] coef, cf_q;
    logic signed [62:0] prod;
    logic signed [65:0] acc;

    // section result: round to Q.16 (the products carry CF + SF bits)
    smp_t res;
    always_comb begin
        logic signed [65:0] r;
        r = (acc + (66'sd1 <<< (CF - 1))) >>> CF;
        res = r[35:0];
    end

    // operand and coefficient for each step (pre-adds included)
    always_comb begin
        opnd = '0;
        coef = '0;
        unique case (step)
            4'd0:  begin coef = C_FM_B;  opnd = 38'(xf[ch]) + 38'(xf1[ch]); end
            4'd1:  begin coef = -C_FM_A1; opnd = 38'(f1[ch]); end
            4'd2:  begin coef = C_HP_B;  opnd = 38'(xp[ch]) - 38'(xp1[ch]); end
            4'd3:  begin coef = -C_HP_A1; opnd = 38'(h1[ch]); end
            4'd4:  begin coef = C_P1_B;  opnd = 38'(h_t) + 38'(h1[ch]); end
            4'd5:  begin coef = -C_P1_A1; opnd = 38'(p1[ch]); end
            4'd6:  begin coef = C_BQ_B;
                         opnd = 38'(p_t) + (38'(p1[ch]) <<< 1) + 38'(p2[ch]); end
            4'd7:  begin coef = -C_BQ_A1; opnd = 38'(q1[ch]); end
            4'd8:  begin coef = -C_BQ_A2; opnd = 38'(q2[ch]); end
            4'd9:  begin coef = C_LO_B;
                         opnd = 38'(f_t) + 38'(q_t) + 38'(m1[ch]); end
            default: begin coef = -C_LO_A1; opnd = 38'(o1[ch]); end
        endcase
    end

    // the last MAC of each section
    function automatic logic sec_end (input logic [3:0] s);
        sec_end = (s == 4'd1) || (s == 4'd3) || (s == 4'd5) ||
                  (s == 4'd8) || (s == 4'd10);
    endfunction

    function automatic logic signed [15:0] sat16 (input smp_t v);
        logic signed [35:0] r;
        r = (v + 36'sd32768) >>> SF;          // round to integer
        if (r > 36'sd32767)       sat16 = 16'sd32767;
        else if (r < -36'sd32768) sat16 = -16'sd32768;
        else                      sat16 = r[15:0];
    endfunction

    always_ff @(posedge clk) begin
        if (rst) begin
            busy <= 1'b0; ch <= 1'b0; step <= '0; ph <= '0;
            acc <= '0; prod <= '0; op_q <= '0; cf_q <= '0;
            f_t <= '0; h_t <= '0; p_t <= '0; q_t <= '0;
            for (int c = 0; c < 2; c++) begin
                xf1[c] <= '0; f1[c] <= '0; xp1[c] <= '0; h1[c] <= '0;
                p1[c] <= '0; p2[c] <= '0; q1[c] <= '0; q2[c] <= '0;
                m1[c] <= '0; o1[c] <= '0; xf[c] <= '0; xp[c] <= '0;
            end
            out_l <= '0; out_r <= '0;
        end else begin
            if (tick && !busy) begin
                xf[0] <= smp_t'(fm_l)  <<< SF;
                xf[1] <= smp_t'(fm_r)  <<< SF;
                xp[0] <= smp_t'(pcm_l) <<< SF;
                xp[1] <= smp_t'(pcm_r) <<< SF;
                busy <= 1'b1; ch <= 1'b0; step <= '0; ph <= '0;
                acc <= '0;
            end else if (busy) begin
                ph <= ph + 2'd1;
                unique case (ph)
                    // the operand mux and the multiplier get a cycle each
                    // (one cycle for both missed 64 MHz by 0.11 ns in the
                    // seed-7 release fit)
                    2'd0: begin op_q <= opnd; cf_q <= coef; end
                    2'd1: prod <= op_q * cf_q;
                    2'd2: acc  <= acc + 66'(prod);
                    default: begin                        // ph 3: advance
                        if (sec_end(step)) begin
                            acc <= '0;
                            unique case (step)
                                4'd1: f_t <= res;
                                4'd3: h_t <= res;
                                4'd5: p_t <= res;
                                4'd8: q_t <= res;
                                default: ;
                            endcase
                        end
                        if (step == 4'(NSTEP - 1)) begin
                            // channel done: shift the delay lines
                            xf1[ch] <= xf[ch];  f1[ch] <= f_t;
                            xp1[ch] <= xp[ch];  h1[ch] <= h_t;
                            p2[ch]  <= p1[ch];  p1[ch] <= p_t;
                            q2[ch]  <= q1[ch];  q1[ch] <= q_t;
                            m1[ch]  <= f_t + q_t;
                            o1[ch]  <= res;
                            if (ch) out_r <= sat16(res);
                            else    out_l <= sat16(res);
                            step <= '0;
                            ch   <= 1'b1;
                            if (ch) busy <= 1'b0;
                        end else
                            step <= step + 4'd1;
                    end
                endcase
            end
        end
    end

endmodule
