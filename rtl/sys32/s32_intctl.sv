// s32_intctl.sv — System 32 interrupt controller (315-5385 subsystem).
//
// References: s32tech, "Interrupt controller" (real-hardware notes);
// behavior cross-checked against MAME segas32 update_irq_state (lowest
// pending unmasked vector wins; enable mask is inverted; an interrupt
// source marks every vector whose source register selects it).
//
// Byte registers at 0xD00000-0xD0000F (V60 low byte lanes), mirrored
// through 0xD7FFFF:
//   0-4  vector source select (3-bit code), vector 0 = highest priority
//   5    unknown (s32tech lists it, function unidentified). The real
//        chip latches writes; they are dropped here, which no readback
//        can observe
//   6    enable mask, 0 = enabled
//   7    pending; write-0-to-ack per bit
//   8-B  Timer A / Timer B 12-bit down-counters (write loads + starts)
//   C-F  access raises the Z80-side interrupt
// Reads return 0xFF except the timer counts (12-bit; 0xFFF once expired).
//
// Sources: 0 vblank-in (line 224), 1 vblank-out (line 0), 2 Z80 comm,
// 3 Timer A, 4 Timer B.
//
// Timers (rates per MAME segas32 int_control_w, consistent with the notes'
// relative speeds): Timer A counts once per 2048 cycles of 16.10795 MHz
// (~7.865 kHz), Timer B once per 256 cycles of 3.125 MHz (~12.21 kHz).
// cen_timer_a / cen_timer_b are those PRE-DIVIDED enables, generated by the
// system top. A zero-duration load leaves the timer untouched, as MAME
// does (int_control_w "if (duration)"); the hardware notes suggest it
// expires immediately instead. Only a real board can settle this.

module s32_intctl (
    input  logic        clk,          // system clock domain
    input  logic        rst,

    // register interface (byte access, offset 0-15)
    input  logic        sel,          // access strobe
    input  logic        we,
    input  logic [3:0]  addr,
    input  logic [7:0]  wdata,
    output logic [7:0]  rdata,

    // interrupt source events (single-cycle pulses)
    input  logic        ev_vblank_in,
    input  logic        ev_vblank_out,
    input  logic        ev_z80_comm,

    // timer clock enables (from the clock generator; pre-divided)
    input  logic        cen_timer_a,  // 16.10795 MHz / 2048
    input  logic        cen_timer_b,  // 3.125 MHz / 256

    // CPU interface
    output logic        irq,          // level: any pending unmasked vector
    output logic [2:0]  irq_vector,   // lowest pending unmasked vector (0-4)

    // Z80-side interrupt trigger (offsets C-F touched)
    output logic        z80_int_pulse
);

    logic [2:0] vecsrc [0:4];
    logic [7:0] mask_q;               // bit = 1 disables
    logic [4:0] pending;
    logic [11:0] ta_cnt, tb_cnt;
    logic        ta_run, tb_run;
    // count configuration registers, separate from the live counters:
    // like MAME (int_control_w cases 8-11), every write recomputes the
    // duration from both stored bytes and restarts the timer
    logic [11:0] ta_load, tb_load;

    // priority resolve: lowest vector number wins
    logic [4:0] eff;
    assign eff = pending & ~mask_q[4:0];
    always_comb begin
        irq = |eff;
        irq_vector = 3'd0;
        if      (eff[0]) irq_vector = 3'd0;
        else if (eff[1]) irq_vector = 3'd1;
        else if (eff[2]) irq_vector = 3'd2;
        else if (eff[3]) irq_vector = 3'd3;
        else if (eff[4]) irq_vector = 3'd4;
    end

    // read side: registers read high except timer counts
    always_comb begin
        unique case (addr)
            4'h8: rdata = ta_run ? ta_cnt[7:0]        : 8'hFF;
            4'h9: rdata = ta_run ? {4'h0, ta_cnt[11:8]} : 8'h0F;
            4'hA: rdata = tb_run ? tb_cnt[7:0]        : 8'hFF;
            4'hB: rdata = tb_run ? {4'h0, tb_cnt[11:8]} : 8'h0F;
            default: rdata = 8'hFF;
        endcase
    end

    // one pending bit per vector; a source event marks every vector
    // whose select register names it
    function automatic logic [4:0] src_hits (input logic [2:0] code);
        src_hits = {vecsrc[4] == code, vecsrc[3] == code,
                    vecsrc[2] == code, vecsrc[1] == code,
                    vecsrc[0] == code};
    endfunction

    // pending set/clear masks, computed combinationally and applied once,
    // so simultaneous events and acks are never lost. A new event beats a
    // simultaneous ack of the same bit (the hardware would re-pend it).
    logic [4:0] pend_set, pend_clr;
    wire ta_expire = ta_run && cen_timer_a && ta_cnt == 12'd0;
    wire tb_expire = tb_run && cen_timer_b && tb_cnt == 12'd0;
    always_comb begin
        pend_set = 5'd0;
        if (ev_vblank_in)  pend_set |= src_hits(3'd0);
        if (ev_vblank_out) pend_set |= src_hits(3'd1);
        if (ev_z80_comm)   pend_set |= src_hits(3'd2);
        if (ta_expire)     pend_set |= src_hits(3'd3);
        if (tb_expire)     pend_set |= src_hits(3'd4);
        pend_clr = (sel && we && addr == 4'h7) ? ~wdata[4:0] : 5'd0;
    end

    integer i;
    always_ff @(posedge clk) begin
        z80_int_pulse <= 1'b0;

        if (rst) begin
            for (i = 0; i < 5; i = i + 1) vecsrc[i] <= 3'd7;
            mask_q  <= 8'hFF;         // everything disabled
            pending <= 5'd0;
            ta_run  <= 1'b0;
            tb_run  <= 1'b0;
            ta_load <= 12'd0;
            tb_load <= 12'd0;
        end else begin
            pending <= (pending & ~pend_clr) | pend_set;

            // timers (pending marks via pend_set above)
            if (ta_run && cen_timer_a) begin
                if (ta_cnt == 12'd0) ta_run <= 1'b0;
                else                 ta_cnt <= ta_cnt - 12'd1;
            end
            if (tb_run && cen_timer_b) begin
                if (tb_cnt == 12'd0) tb_run <= 1'b0;
                else                 tb_cnt <= tb_cnt - 12'd1;
            end

            // register writes
            if (sel && we) begin
                unique case (addr)
                    4'h0, 4'h1, 4'h2, 4'h3, 4'h4:
                        vecsrc[addr[2:0]] <= wdata[2:0];
                    4'h6: mask_q <= wdata;
                    4'h7: ;                   // ack applied via pend_clr
                    // zero duration leaves the timer untouched (MAME
                    // "if (duration)"; see the header)
                    4'h8: begin
                        ta_load[7:0] <= wdata;
                        if ({ta_load[11:8], wdata} != 12'd0) begin
                            ta_cnt <= {ta_load[11:8], wdata};
                            ta_run <= 1'b1;
                        end
                    end
                    4'h9: begin
                        ta_load[11:8] <= wdata[3:0];
                        if ({wdata[3:0], ta_load[7:0]} != 12'd0) begin
                            ta_cnt <= {wdata[3:0], ta_load[7:0]};
                            ta_run <= 1'b1;
                        end
                    end
                    4'hA: begin
                        tb_load[7:0] <= wdata;
                        if ({tb_load[11:8], wdata} != 12'd0) begin
                            tb_cnt <= {tb_load[11:8], wdata};
                            tb_run <= 1'b1;
                        end
                    end
                    4'hB: begin
                        tb_load[11:8] <= wdata[3:0];
                        if ({wdata[3:0], tb_load[7:0]} != 12'd0) begin
                            tb_cnt <= {wdata[3:0], tb_load[7:0]};
                            tb_run <= 1'b1;
                        end
                    end
                    4'hC, 4'hD, 4'hE, 4'hF: z80_int_pulse <= 1'b1;
                    default: ;
                endcase
            end
            if (sel && !we && addr >= 4'hC)
                z80_int_pulse <= 1'b1;   // reads also trigger
        end
    end

endmodule
